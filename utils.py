def getdata(plc,tag,addr,oldval):
    suffix = 2
    data_type_lookup = {tag[0]: tag[2] for tag in SCADA_TAGS}
    data_type = data_type_lookup[tag]
    # print(data_type)
    val = 0
    print('Fetching tag:', tag)
    try:
        if data_type == 'INT':
            val = int(plc.receive((tag, suffix),addr))
            # print('Fetched value:', val)
        elif data_type == 'REAL':
            val = float(plc.receive((tag, suffix),addr))
        print('Fetched value:', val)
    except:
        print('Could not fetch the value of', tag)
        val = oldval
        print('Keeping stale value:', val)
    return val

def setdata(plc, tag,addr,value):
    suffix = 2
    data_type_lookup = {tag[0]: tag[2] for tag in SCADA_TAGS}
    data_type = data_type_lookup[tag]
    print('Setting tag:', tag, 'to', value)
    try:
        if data_type == 'INT':
            plc.send((tag,suffix), int(value), addr)
        elif data_type == 'REAL':
            plc.send((tag,suffix), float(value), addr)
    except:
        print('Could not set the value of', tag, 'to', value)


